function special_content(): array
{
    global $specialTranslations;
    $language = getCurrentLanguage();
    return $specialTranslations[$language] ?? $specialTranslations['en'];
}

function special_t(string $key, string $default = ''): string
{
    $content = special_content();
    return isset($content[$key]) && is_string($content[$key]) ? $content[$key] : $default;
}

